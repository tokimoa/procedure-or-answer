"""exp26 — method-corruption with the model's OWN-STYLE exemplars (repairs exp18's
templated-exemplar protocol exception).

exp18 established method-corruption damage with hand-templated exemplars — the one
protocol exception in the paper, and the style the pilot flagged as confound-prone
(which is also why Ministral-3-3B had to be excluded there). exp26 re-runs the
method-vs-answer contrast with every STORED exemplar generated by the model itself,
so the style confound is gone and Ministral-3-3B is back in.

Pool construction (matched elicitation for both methods): the model solves fresh
pool problems after seeing k=3 templated demonstrations of the target procedure
(correct: multiply; wrong: add) — the exp18 test-time condition — and we KEEP its
own generation iff it coherently executes that procedure:
  correct      : parsed answer == gold, body shows the product total,
                 body does NOT show the additive total
  wrong_method : parsed answer == the additive method's result (integer- or
                 float-rounding path), body shows the additive total,
                 body does NOT show the product total
The templated seeds never enter the store; only the model's own text does.
Retention rates are recorded. Test items are presented with NO hint and scored
against the true gold (main protocol).

Conditions (same as exp18): nomem / worked_correct / worked_ans_corrupt (anchored
ANSWER-line corruption of worked_correct) / worked_wrong_method.

Usage:
  HF_HUB_OFFLINE=1 .venv/bin/python experiments/exp26_ownstyle_method.py \
      --models llama3.2-3b,phi4-mini,ministral3-3b,granite4.1-8b --seeds 5
"""
import argparse
import json
import math
import os
import re
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from rsiguard.backends import MLXBackend, mx_seed
from experiments.models import MODELS
from experiments.memory import solve as mem_solve, build_prompt, _ANS

CONDS = ["nomem", "worked_correct", "worked_ans_corrupt", "worked_wrong_method"]


def make_item(rng):
    """Same generator as exp18/_pool_arith_hard, keeping the parameters so both
    procedures' expected values are computable."""
    P, B, I = int(rng.integers(3, 9)), int(rng.integers(4, 9)), int(rng.integers(3, 8))
    dmg, cr = int(rng.integers(1, 4)) * 5, int(rng.integers(6, 12))
    total = P * B * I
    good = total - (total * dmg) // 100
    ans = good // cr
    wt = P + B + I
    wg = wt - (wt * dmg) // 100
    q = (f"A warehouse has {P} pallets, each holding {B} boxes of {I} items. {dmg}% of "
         f"all items are damaged and removed. The rest are packed into crates of {cr} "
         f"(leftover items are not crated). How many full crates?")
    return {"problem": q, "gold": ans, "total": total,
            "wrong_total": wt,
            "wrong_gold_int": wg // cr,
            "wrong_gold_float": math.floor(wt * (1 - dmg / 100) / cr)}


def template_sol(it, method):
    """exp18's hand-templated demonstrations — used ONLY to seed elicitation."""
    # recover dmg/cr from the expected values is fragile; re-derive from the problem
    m = re.search(r"(\d+)% of all items.*crates of (\d+)", it["problem"])
    dmg, cr = int(m.group(1)), int(m.group(2))
    pbi = re.search(r"(\d+) pallets, each holding (\d+) boxes of (\d+) items", it["problem"])
    P, B, I = int(pbi.group(1)), int(pbi.group(2)), int(pbi.group(3))
    if method == "correct":
        total = P * B * I
        good = total - (total * dmg) // 100
        return (f"Total items = {P}*{B}*{I} = {total}. Damaged = {dmg}% of {total} = "
                f"{(total*dmg)//100}. Good = {good}. Crates = {good}//{cr} = {good//cr}.\n"
                f"ANSWER: {good//cr}")
    wt = P + B + I
    wg = wt - (wt * dmg) // 100
    return (f"Total items = {P}+{B}+{I} = {wt}. Damaged = {dmg}% of {wt} = "
            f"{(wt*dmg)//100}. Good = {wg}. Crates = {wg}//{cr} = {wg//cr}.\n"
            f"ANSWER: {wg//cr}")


def _shows(body, value):
    return re.search(rf"(?<![\d.]){value}(?![\d.])", body) is not None


def elicit(be, item, method, seed_demos):
    """One elicited own-style solution under k=3 templated seeds of the target
    method; returns the model's text iff it coherently executes that method."""
    txt = be.gen(build_prompt(item["problem"], seed_demos))
    m = _ANS.search(txt)
    if not m:
        return None
    a, body = int(m.group(1)), txt[:m.start()]
    if method == "correct":
        if a != item["gold"]:
            return None
        if not _shows(body, item["total"]) or _shows(body, item["wrong_total"]):
            return None
    else:
        if a not in (item["wrong_gold_int"], item["wrong_gold_float"]):
            return None
        if not _shows(body, item["wrong_total"]) or _shows(body, item["total"]):
            return None
    return txt


def build_matched_pools(be, target, cand_cap, rng, k_seed=3, verbose="", decouple=False):
    """Pool items where BOTH elicitations verify, so all memory conditions
    demonstrate on the SAME problems (exp18's matched-items design). With
    decouple=True each pool fills independently from its own verified items ---
    for models whose wrong-method retention is too low to satisfy the matched
    requirement (they cannot coherently execute the wrong procedure); the
    correct/ans-corrupt legs then still run, and wrong-method is reported
    against whatever pool exists."""
    correct_pool, wrong_pool = [], []
    tried = ok_c = ok_w = 0
    while tried < cand_cap:
        if decouple:
            if len(correct_pool) >= target and len(wrong_pool) >= target:
                break
        elif len(correct_pool) >= target:
            break
        it = make_item(rng)
        seeds = [make_item(rng) for _ in range(k_seed)]
        demos_c = [{"problem": s["problem"], "sol": template_sol(s, "correct")} for s in seeds]
        demos_w = [{"problem": s["problem"], "sol": template_sol(s, "wrong")} for s in seeds]
        tried += 1
        c = elicit(be, it, "correct", demos_c)
        if c is not None:
            ok_c += 1
        w = elicit(be, it, "wrong", demos_w)
        if w is not None:
            ok_w += 1
        if decouple:
            if c is not None and len(correct_pool) < target:
                correct_pool.append({"problem": it["problem"], "gold": it["gold"], "sol": c})
            if w is not None and len(wrong_pool) < target:
                wrong_pool.append({"problem": it["problem"], "gold": it["gold"], "sol": w})
        elif c is not None and w is not None:
            correct_pool.append({"problem": it["problem"], "gold": it["gold"], "sol": c})
            wrong_pool.append({"problem": it["problem"], "gold": it["gold"], "sol": w})
    stats = {"tried": tried, "verified_correct": ok_c, "verified_wrong": ok_w,
             "pool": len(correct_pool), "pool_wrong": len(wrong_pool),
             "decoupled": decouple}
    print(f"    {verbose} pools: {stats}", flush=True)
    return correct_pool, wrong_pool, stats


def ans_corrupt(pool, rng):
    out = []
    for it in pool:
        bad = it["gold"] + int(rng.choice([-2, -1, 1, 2, 3]))
        sol, nsub = re.subn(r"ANSWER:\s*-?\d+", f"ANSWER: {bad}", it["sol"])
        if nsub == 0:
            sol = it["sol"] + f"\nANSWER: {bad}"
        out.append({"problem": it["problem"], "gold": it["gold"], "sol": sol})
    return out


def acc(be, mem, test, k, rng):
    corr = []
    for t in test:
        ex = [] if mem is None else [mem[i] for i in rng.permutation(len(mem))[:k]]
        a, _, _ = mem_solve(be, t["problem"], ex)
        corr.append(1.0 if a == t["gold"] else 0.0)
    return float(np.mean(corr))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--models", default="llama3.2-3b,phi4-mini,ministral3-3b,granite4.1-8b")
    ap.add_argument("--pooln", type=int, default=24)
    ap.add_argument("--cand-cap", type=int, default=90)
    ap.add_argument("--test", type=int, default=24)
    ap.add_argument("--k", type=int, default=3)
    ap.add_argument("--seeds", type=int, default=5)
    ap.add_argument("--max-tokens", type=int, default=256)
    ap.add_argument("--decouple", action="store_true",
                    help="fill each pool independently (see build_matched_pools)")
    ap.add_argument("--out", default="results/exp26_ownstyle.json")
    args = ap.parse_args()

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    records = []
    for key in [m.strip() for m in args.models.split(",") if m.strip()]:
        print(f"\n### model={key}", flush=True)
        try:
            be = MLXBackend(MODELS[key], max_tokens=args.max_tokens)
        except Exception as e:
            print(f"  !! load failed: {e}", flush=True)
            continue
        for s in range(args.seeds):
            mx_seed(s)
            correct_pool, wrong_pool, pstats = build_matched_pools(
                be, args.pooln, args.cand_cap, np.random.default_rng(s + 11),
                k_seed=args.k, verbose=f"seed{s}", decouple=args.decouple)
            trng = np.random.default_rng(s + 7777)
            test = [make_item(trng) for _ in range(args.test)]
            mems = {"worked_correct": correct_pool,
                    "worked_ans_corrupt": ans_corrupt(correct_pool, np.random.default_rng(s)),
                    "worked_wrong_method": wrong_pool}
            row = {"model": key, "seed": s, **pstats,
                   "nomem": acc(be, None, test, 0, np.random.default_rng(s))}
            for c in CONDS[1:]:
                row[c] = acc(be, mems[c] if mems[c] else None, test,
                             args.k if mems[c] else 0, np.random.default_rng(s + 1))
            records.append(row)
            print(f"  seed{s}: " + " ".join(f"{c}={row[c]:.2f}" for c in CONDS), flush=True)
            json.dump(records, open(args.out, "w"), indent=2)  # checkpoint per seed
        del be

    json.dump(records, open(args.out, "w"), indent=2)
    print("\n" + "=" * 70)
    print(" exp26 — OWN-STYLE method-corruption (mean over seeds)")
    print("=" * 70)
    print(f"{'model':<16}" + "".join(f"{c.replace('worked_',''):>16}" for c in CONDS))
    for key in [m.strip() for m in args.models.split(",")]:
        rs = [r for r in records if r["model"] == key]
        if not rs:
            continue
        print(f"{key:<16}" + "".join(f"{np.mean([r[c] for r in rs]):>16.2f}" for c in CONDS))
    print("=" * 70)
    print("exp18 replicates own-style if wrong_method < correct ≈ ans_corrupt")
    print(f"saved -> {args.out}")


if __name__ == "__main__":
    main()
